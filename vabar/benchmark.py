def _public_module(cls: type) -> str:
    """Where to import ``cls`` from: ``robosimstudio.specs`` when it is exported there, else its own module."""
    try:
        if getattr(importlib.import_module("robosimstudio.specs"), cls.__name__, None) is cls:
            return "robosimstudio.specs"
    except ImportError:  # pragma: no cover
        pass
    return cls.__module__


def _py(value: Any, imports: dict[str, set[str]], indent: int = 0) -> str:
    """``value`` as Python source that evaluates back to it. Dataclasses state only non-default fields."""
    if dataclasses.is_dataclass(value) and not isinstance(value, type):
        cls = type(value)
        imports.setdefault(_public_module(cls), set()).add(cls.__name__)
        parts = []
        for f in dataclasses.fields(value):
            current = getattr(value, f.name)
            if f.default is not dataclasses.MISSING:
                default = f.default
            elif f.default_factory is not dataclasses.MISSING:
                default = f.default_factory()
            else:
                default = dataclasses.MISSING
            if f.init and current != default:
                parts.append(f"{f.name}={_py(current, imports, indent + 1)}")
        if indent == 0 and parts:
            pad = " " * 8
            return f"{cls.__name__}(\n" + "".join(f"{pad}{p},\n" for p in parts) + "    )"
        return f"{cls.__name__}({', '.join(parts)})"
    if isinstance(value, tuple):
        inner = ", ".join(_py(v, imports, indent + 1) for v in value)
        return f"({inner},)" if len(value) == 1 else f"({inner})"
    if isinstance(value, list):
        return "[" + ", ".join(_py(v, imports, indent + 1) for v in value) + "]"
    if isinstance(value, dict):
        return "{" + ", ".join(f"{_py(k, imports)}: {_py(v, imports, indent + 1)}" for k, v in value.items()) + "}"
    if isinstance(value, Path):
        return repr(str(value))
    if value is None or isinstance(value, bool | int | float | str):
        return repr(value)
    raise TypeError(f"cannot write a {type(value).__name__} into a job file: {value!r}")


def write_jobs_file(path: Path, specs: list, *, header: list[str] = ()) -> Path:
    """A job file the runner's ``--jobs`` loads: ``JOBS: list[JobSpec]``, one per spec, in order."""
    imports: dict[str, set[str]] = {}
    body = "".join(f"    {_py(spec, imports)},\n" for spec in specs)
    lines = ["# Generated by `vabar bench`. Regenerate it rather than edit it.", *(f"# {h}" for h in header), ""]
    lines += [f"from {module} import {', '.join(sorted(names))}" for module, names in sorted(imports.items())]
    lines += ["", "JOBS = [", body.rstrip("\n"), "]", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines))
    return path


def job_specs(plan: Plan, flags) -> list:
    """Each job as the ``JobSpec`` its ``vabar run`` command produces: the runner's own parser and ``job_from_args``."""
    from ._upstream import bench_run
    from .run import with_default_renderer

    specs = []
    for job in plan.jobs:
        args = flags.parser.parse_args(with_default_renderer(job.argv + plan.extra))
        spec = bench_run.job_from_args(args)
        if job.fields:
            spec = dataclasses.replace(spec, **job.fields)
        specs.append(spec)
    names = [s.name for s in specs]
    clash = sorted({n for n in names if names.count(n) > 1})
    if clash:
        raise SystemExit(f"[bench] two jobs would share run directories {clash}; does a variant mapping collide?")
    return specs


# ------------------------------------------------------------------ running a cell
REFUSED = "CannotReplicate"


def _results(run_dir: Path) -> list[dict]:
    path = run_dir / "episode_results.jsonl"
    if not path.is_file():
        return []
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def _refused(specs: list, out: Path, raised: BaseException | None) -> list[str]:
    """The jobs that asked for a wave and were refused one: by their rows, or by what the runner raised."""
    refused = [
        s.name
        for s in specs
        if s.num_worlds > 1 and any(REFUSED in str(r.get("error", "")) for r in _results(out / s.name))
    ]
    if raised is not None:
        message = str(raised)
        named = [s for s in specs if s.num_worlds > 1 and message.startswith(f"{s.task} ")]
        unrun = [s for s in specs if s.num_worlds > 1 and not _results(out / s.name)]
        for s in named or unrun[:1]:
            if s.name not in refused:
                refused.append(s.name)
    return refused


def run_plan(plan: Plan, flags) -> int:
    """Run a planned cell: write the job file and provenance, invoke the runner once, re-run what refused a wave."""
    from . import install

    cfg.activate(plan.config)
    install()
    for line in describe(plan, flags):
        print(line.removeprefix("# "))
    env: dict[str, str] = {}
    for job in plan.jobs:
        for k, v in job.env.items():
            if env.setdefault(k, v) != v:
                print(f"[bench] warning: jobs disagree about {k}; the run uses {env[k]!r}", file=sys.stderr)
    effective = cfg.apply_env(plan.config, extra=env, tasks=sorted({job.task for job in plan.jobs}))
    specs = job_specs(plan, flags)
    from robosimstudio_bench.taskbuild.registry import list_tasks

    missing = sorted({s.task for s in specs} - set(list_tasks()))
    if missing:
        raise SystemExit(f"[bench] config {plan.config.name} maps instances onto unregistered tasks {missing}")
    for spec in specs:
        if (plan.out / spec.name / "episode_results.jsonl").exists():
            print(f"[bench] warning: {plan.out / spec.name} already holds results; this run appends to them")

    record = {
        "cell": plan.cell,
        "solve": plan.solve,
        "workers": plan.workers,
        "workers_why": plan.workers_why,
        "env": effective,
        "dropped": list(dict.fromkeys(plan.dropped)),
        "jobs": [
            {
                "name": s.name,
                "task": j.task,
                "instance_task": j.instance_task,
                "episodes": j.episodes,
                "num_worlds": s.num_worlds,
                "argv": j.argv + plan.extra,
            }
            for j, s in zip(plan.jobs, specs, strict=True)
        ],
    }
    with contextlib.ExitStack() as stack:
        record["mps"] = stack.enter_context(mps.daemon(plan.config.runtime["mps"] and plan.workers > 1))
        # Entered after MPS, so it exits first: the shared servers are MPS clients.
        record["tool_servers"] = stack.enter_context(
            toolshare.shared_tool_servers(plan.config.runtime["share_tool_servers"] and plan.workers > 1)
        )
        return _run_attempts(plan, flags, specs, record)


def _run_attempts(plan: Plan, flags, specs: list, record: dict) -> int:
    """Invoke the runner on the pending jobs; re-run at one world what refused a wave."""
    from .run import invoke

    pending, jobs_file, status = specs, plan.jobs_file, 0
    for attempt in range(len(specs) + 1):
        write_jobs_file(jobs_file, pending, header=[f"{plan.cell}, config {plan.config.name}"])
        argv = plan.invocation(flags, jobs_file)
        cfg.write_provenance(plan.out, plan.config, runner_argv=argv, **record)
        for spec in pending:
            cfg.write_provenance(plan.out / spec.name, plan.config, runner_argv=argv, job=spec.name, **record)
        raised = None
        try:
            status |= invoke(argv)
        except Exception as exc:
            # A serial run raises the refusal out of the runner (a pool writes
            # it into error rows instead). Only that one is handled here.
            if type(exc).__name__ != REFUSED:
                raise
            raised = exc
        refused = _refused(pending, plan.out, raised)
        if not refused:
            if raised is not None:
                raise raised
            return status
        # The refusal is a property of the scene's entities, so it holds for the
        # suite: every pending job of that suite drops to one world.
        suites = {s.task.split("/")[0] for s in pending if s.name in refused}
        print(
            f"[bench] {', '.join(refused)}: the scene refuses to replicate; re-running at one world. "
            f"Add `num_worlds = 1` under {', '.join(f'[suites.{s}]' for s in sorted(suites))} in the config "
            "to skip the attempt."
        )
        rerun = []
        for spec in pending:
            done = bool(_results(plan.out / spec.name))
            if spec.name in refused:
                aside = plan.out / f"{spec.name}.refused-wave"
                shutil.rmtree(aside, ignore_errors=True)
                if (plan.out / spec.name).exists():
                    (plan.out / spec.name).rename(aside)
            elif done:
                continue
            one = spec.task.split("/")[0] in suites
            rerun.append(dataclasses.replace(spec, num_worlds=1) if one else spec)
        for job in record["jobs"]:
            if job["task"].split("/")[0] in suites:
                job["num_worlds"] = 1
        record["fallback"] = record.get("fallback", []) + refused
        pending, jobs_file = rerun, plan.out / f"jobs.retry{attempt + 1}.py"
        if not pending:
            return status
    return status


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="vabar bench", description=__doc__.splitlines()[0], allow_abbrev=False)
    parser.add_argument("--list", action="store_true", help="list the cells and their instance counts")
    parser.add_argument("--cell", help="task_class/L<level>, e.g. tool_hanging/L1")
    parser.add_argument("--solve", default="graph", help="graph (the cell's reference graph), routine, idle, ...")
    parser.add_argument("--limit", type=int, default=0, help="run only the first N instances")
    parser.add_argument("--print", action="store_true", help="print the resolved jobs as vabar run commands and exit")
    parser.add_argument("--verify", action="store_true", help="check resets against the frozen transforms")
    parser.add_argument(
        "--config",
        default=None,
        help=f"experiment config: {', '.join(cfg.names())} or a .toml path (default: $VABAR_CONFIG, else default)",
    )
    parser.add_argument(
        "--set", action="append", default=[], metavar="KEY=VALUE", help="override one config key; repeatable"
    )
    parser.add_argument(
        "--no-warmup", action="store_true", help="do not compile the cell's scenes on its first run here"
    )
    parser.add_argument("--build", action="store_true", help=argparse.SUPPRESS)
    args, extra = parser.parse_known_args(argv)

    if args.build:
        MANIFEST.write_text(json.dumps(build(), indent=1) + "\n")
        print(f"wrote {MANIFEST.relative_to(REPO)}")
        return 0
    manifest = load()
    if args.list or not args.cell:
        for key, cell in manifest["cells"].items():
            print(f"{key:20s} {len(cell['instances']):3d}  {cell['suite']:16s} graph={cell['graph']}")
        return 0
    if args.cell not in manifest["cells"]:
        print(f"[bench] no cell {args.cell!r}; the cells are {list(manifest['cells'])}", file=sys.stderr)
        return 2
    cell = manifest["cells"][args.cell]
    if not cell["instances"]:
        print(f"{args.cell}: {cell['selection']}. {cell['notes']}", file=sys.stderr)
        return 2
    try:
        config = cfg.resolve(args.config, args.set)
    except cfg.ConfigError as exc:
        print(f"[bench] {exc}", file=sys.stderr)
        return 2
    if args.verify:
        cfg.activate(config)
        rows = verify(cell, limit=args.limit)
        for name, ok, detail in rows:
            print(f"{'ok ' if ok else 'BAD'} {name}: {detail}")
        return 0 if all(ok for _, ok, _ in rows) else 1

    from .run import runner_flags

    flags = runner_flags()
    if args.print:
        # The jobs' budgets come from the registry, which must see the config's rewrites.
        cfg.activate(config)
    plan = plan_cell(args.cell, cell, config, solve=args.solve, limit=args.limit, extra=extra, flags=flags)
    if args.print:
        sys.stdout.flush()
        for line in describe(plan, flags):
            print(line, file=sys.stderr)
        sys.stderr.flush()
        for job in plan.jobs:
            print(plan.line(job))
        return 0
    if args.solve == "graph" and not args.no_warmup:
        from .warmup import ensure_warm

        ensure_warm(args.cell, config, extra)
    return run_plan(plan, flags)


if __name__ == "__main__":
    if "--build" in sys.argv:
        raise SystemExit(main(["--build"]))
    raise SystemExit(main())
