"""The benchmark: twelve cells (six task classes x two levels), N instances each.

A cell's instances are ``(task, episode)`` pairs on the registered suites, so a
benchmark run is an ordinary RoboSimStudio run over episode lists and needs no
loader of its own. Every suite seeds its sampler from ``seed + episode``, which
is what lets a frozen instance be named by its episode: the per-instance
documents under ``benchmark/`` and their manifests record the same draws (and,
where they were exported, the exact initial transforms), and
:func:`verify` checks a reset against them.

    python -m vabar bench --list                                  # the cells
    python -m vabar bench --cell tool_hanging/L1 --solve graph    # under the `default` config
    python -m vabar bench --cell tool_hanging/L1 --config paper   # the v1.0 protocol
    python -m vabar bench --cell cable_insertion/L2 --solve graph --limit 3
    python -m vabar bench --cell tool_hanging/L1 --print           # the resolved jobs, one per task

**A cell is one runner invocation.** :func:`plan_cell` turns the cell into one
job per task its instances live on -- the cell's graph and flags, with the
experiment config (:mod:`vabar.config`) applied: its variant mapping, runtime
flags, per-suite overrides, ``num_worlds`` (``min(config, the task's
instances)``) and environment. :func:`run_plan` writes them to a job file
(``JOBS: list[JobSpec]``) under the run's output directory --
``outputs/<config>/<cell>/`` unless ``--out`` says otherwise -- and calls the
vendored runner once with ``--jobs`` and the config's ``--workers``, so a pool
of workers pulls waves from the whole cell instead of the cell's tasks each
paying for a process of their own. A pool orders its queue job by job, so the
jobs go longest first (by step budget). A task whose scene refuses to replicate
(``CannotReplicate``) is re-run at one world.

``--print`` writes each job as the equivalent ``vabar run`` command on stdout,
and how they are scheduled (the one invocation, workers, the job file) on
stderr. Under ``--config paper`` stdout is exactly what v1.0 printed.

``benchmark/vabar_v1.json`` is generated by ``python -m vabar.benchmark --build``
from the frozen specs; edit those, not the JSON. It is the published record of
what each cell measures, flags included, and the configs override it rather
than rewrite it.
"""

