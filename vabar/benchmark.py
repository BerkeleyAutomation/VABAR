INVOCATION_FLAGS = ("--devices", "--stagger", "--threads-per-worker", "--view", "--view-port", "--task-root")
"""Runner flags that belong to the one invocation rather than to each job (besides --workers and --out)."""


@dataclass
class Job:
    """One task's share of a cell: what ``vabar run`` would be asked, with the config applied.

    Attributes:
        instance_task: The task the frozen instances name.
        task: The task run: ``instance_task`` after the config's variant mapping.
        episodes: The instances' episodes on it.
        argv: The ``vabar run`` arguments, without the caller's extras or ``--workers``.
        env: Environment the job asks for: the cell's (for a graph), then the config's.
        num_worlds: Worlds per wave.
        fields: ``JobSpec`` fields the config sets that the runner has no flag for yet.
        budget: Its step budget, the proxy for how long it runs (0 when not looked up).
    """

    instance_task: str
    task: str
    episodes: list[int]
    argv: list[str]
    env: dict[str, str]
    num_worlds: int = 1
    fields: dict[str, Any] = field(default_factory=dict)
    budget: int = 0

    @property
    def units(self) -> int:
        """Waves (episodes, for a serial job): what a pool worker pulls."""
        return math.ceil(len(self.episodes) / max(1, self.num_worlds))


@dataclass
class Plan:
    """A cell, resolved: its jobs in run order, and the one runner invocation that runs them."""

    cell: str
    config: cfg.Config
    solve: str
    jobs: list[Job]
    extra: list[str]
    workers: int
    workers_why: str
    out: Path
    dropped: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)

    @property
    def jobs_file(self) -> Path:
        return self.out / "jobs.py"

    def invocation(self, flags, jobs_file: Path | None = None) -> list[str]:
        """The vendored runner's arguments: the job file, ``--workers``, ``--out``, the caller's invocation flags."""
        argv = ["--jobs", str(jobs_file or self.jobs_file), "--workers", str(self.workers), "--out", str(self.out)]
        return flags.merge(argv, self.extra, replace=True, skip=_job_level(flags, self.extra))

    def line(self, job: Job) -> str:
        """``job`` as one ``vabar run`` command, environment first; what ``--print`` writes."""
        env = dict(job.env)
        if self.config.rewrites(job.task):
            # Physics, cameras or a budget the command line cannot state: the
            # command reproduces the job only under the same config.
            env[cfg.ENV_CONFIG] = self.config.ref
            if self.config.overrides:
                env[cfg.ENV_SET] = json.dumps(list(self.config.overrides))
        argv = list(job.argv)
        if self.workers > 1 and "--workers" not in _flag_names(self.extra):
            argv += ["--workers", str(self.workers)]
        prefix = "".join(f"{k}={shlex.quote(v)} " for k, v in env.items())
        return prefix + "python -m vabar run " + shlex.join(argv + self.extra)


def _flag_names(argv: list[str]) -> set[str]:
    return {a.partition("=")[0] for a in argv if a.startswith("--")}


def _job_level(flags, extra: list[str]) -> set[str]:
    """The ``dest`` of every flag in ``extra`` that is a job's rather than the invocation's."""
    invocation = {flags.dest(f) for f in (*INVOCATION_FLAGS, "--workers", "--out", "--jobs") if flags.accepts(f)}
    return {key for key, _ in flags.items(extra) if key is not None and key not in invocation}


def _registry_budget(task: str) -> int:
    from . import install

    install()
    from robosimstudio_bench.taskbuild.registry import get_task

    return int(get_task(task).max_steps)


def plan_cell(
    key: str,
    cell: dict,
    config: cfg.Config,
    *,
    solve: str = "graph",
    limit: int = 0,
    extra: list[str] = (),
    flags=None,
    budget: Callable[[str], int] | None = None,
    workers: Callable[[cfg.Config, int], tuple[int, str]] | None = None,
) -> Plan:
    """Resolve a cell under ``config`` into jobs and one invocation. Builds nothing and runs nothing.

    Args:
        key: The cell, ``task_class/L<level>``.
        cell: Its manifest entry.
        config: The experiment config.
        solve: ``graph`` (the cell's reference graph and flags) or another solution.
        limit: Only the first N instances.
        extra: Further ``vabar run`` flags; they win over the cell and the config.
        flags: The runner's flags (:func:`vabar.run.runner_flags`).
        budget: A task's own step budget, for ordering jobs whose flags name
            none; defaults to the registry's ``TaskSpec.max_steps``.
        workers: How many processes; defaults to :func:`vabar.config.resolve_workers`.
    """
    from .run import RENDER_FLAGS, config_flags, runner_flags

    flags = flags or runner_flags()
    extra = list(extra)
    groups = _groups(cell["instances"][: limit or None])
    if "--name" in _flag_names(extra) and len(groups) > 1:
        raise SystemExit(f"[bench] --name names one run directory and {key} runs {len(groups)} jobs; use --out")
    user = {k for k, _ in flags.items(extra) if k is not None}
    if any(a.partition("=")[0] in RENDER_FLAGS for a in extra):
        user.add(flags.dest("--renderer"))
    user_worlds = flags.value(extra, "--num-worlds")

    jobs: list[Job] = []
    dropped: list[str] = []
    notes: list[str] = []
    for instance_task, episodes in groups.items():
        task = config.map_task(instance_task)
        if task != instance_task:
            notes.append(f"config {config.name} runs {instance_task} as {task}")
        base = _cell_argv(cell, task, episodes, solve)
        vision = flags.value(base + extra, "--perception") == "vision"
        add, lost, fields = config_flags(config, task, solve=solve, vision=vision, flags=flags, bench=True)
        dropped += lost
        worlds = int(user_worlds) if user_worlds else min(config.num_worlds(task), len(episodes))
        if worlds > 1 and not user_worlds:
            add += ["--num-worlds", str(worlds)]
        jobs.append(
            Job(
                instance_task=instance_task,
                task=task,
                episodes=list(episodes),
                argv=flags.merge(base, add, replace=True, skip=user),
                env={**(cell.get("env", {}) if solve == "graph" else {}), **config.env(task)},
                num_worlds=max(1, worlds),
                fields=fields,
            )
        )

    units = sum(job.units for job in jobs)
    given = flags.value(extra, "--workers")
    if given:
        count, why = max(1, int(given)), "--workers"
    else:
        count, why = (workers or functools.partial(cfg.resolve_workers, suite=cell["suite"]))(config, units)
    if count > 1:
        # A pool queues its units job by job, so the longest job goes first and
        # the short ones fill in behind it rather than leaving a straggler. A
        # serial run (v1.0's) keeps the manifest's order.
        lookup = budget or _registry_budget
        for job in jobs:
            stated = flags.value(job.argv + extra, "--max-steps")
            job.budget = int(stated) if stated and int(stated) > 0 else lookup(job.task)
        jobs.sort(key=lambda j: (-j.budget, -j.units))
    given_out = flags.value(extra, "--out")
    out = Path(given_out) if given_out else Path("outputs") / config.name / key
    return Plan(
        cell=key,
        config=config,
        solve=solve,
        jobs=jobs,
        extra=extra,
        workers=count,
        workers_why=why,
        out=out,
        dropped=dropped,
        notes=notes,
    )


def describe(plan: Plan, flags) -> list[str]:
    """The schedule, for a person: what ``--print`` writes to stderr and a run prints first."""
    from .run import dropped_warning

    episodes = sum(len(j.episodes) for j in plan.jobs)
    units = sum(j.units for j in plan.jobs)
    lines = [
        f"# {plan.cell} under config {plan.config.name} (sha256 {plan.config.sha256[:12]}"
        + (f", --set {' '.join(plan.config.overrides)}" if plan.config.overrides else "")
        + f"): {len(plan.jobs)} jobs, {episodes} episodes, {units} {'waves' if units != episodes else 'units'}",
        f"# workers {plan.workers} ({plan.workers_why})"
        + (", sharing the GPU through MPS" if plan.config.runtime["mps"] and plan.workers > 1 else "")
        + (
            ", one SAM 3 / GroundingDINO server for all of them"
            if plan.config.runtime["share_tool_servers"] and plan.workers > 1
            else ""
        )
        + f"; output {plan.out}",
        "# one runner invocation: python -m vabar run " + shlex.join(plan.invocation(flags)),
    ]
    for job in plan.jobs:
        worlds = f", {job.num_worlds} worlds/wave" if job.num_worlds > 1 else ""
        budget = f", budget {job.budget} steps" if job.budget else ""
        count = f"{len(job.episodes)} episode{'s' if len(job.episodes) != 1 else ''}"
        lines.append(f"#   {job.task}: {count}{worlds}{budget}")
    lines += [f"# {note}" for note in plan.notes]
    if plan.config.name == "paper":
        lines.append(
            "# --config paper prints the v1.0 commands verbatim; on this checkout run them under VABAR_CONFIG=paper"
        )
    warning = dropped_warning(plan.config, plan.dropped, via_jobs=set().union(*(j.fields for j in plan.jobs)))
    if warning:
        lines += [f"# {line}" for line in warning.splitlines()]
    return lines


