"""The benchmark: twelve cells (six task classes x two levels), N instances each.

A cell's instances are ``(task, episode)`` pairs on the registered suites, so a
benchmark run is an ordinary RoboSimStudio run over episode lists and needs no
loader of its own. Every suite seeds its sampler from ``seed + episode``, which
is what lets a frozen instance be named by its episode: the per-instance
documents under ``benchmark/`` and their manifests record the same draws (and,
where they were exported, the exact initial transforms), and
:func:`verify` checks a reset against them.

    python -m vabar bench --list                                  # the cells
    python -m vabar bench --cell tool_hanging/L1 --solve graph --workers 8 --out outputs/bench
    python -m vabar bench --cell cable_insertion/L2 --solve graph --limit 3
    python -m vabar bench --cell tool_hanging/L1 --print           # the bench_run commands, one per task

``benchmark/vabar_v1.json`` is generated by ``python -m vabar.benchmark --build``
from the frozen specs; edit those, not the JSON.
"""

from __future__ import annotations

import argparse
import json
import os
import shlex
import sys
from collections import OrderedDict

from . import REPO

MANIFEST = REPO / "benchmark" / "vabar_v1.json"
SPECS = REPO / "benchmark"

# The flags the reference graphs were evaluated under: no sim.* ground truth,
# perception from the cameras, and a bus watchdog long enough for a cuRobo plan
# (the default 30 s of wall clock can expire mid-solve on a busy machine).
UNPRIVILEGED = ["--no-privileged", "--perception", "vision", "--bus-timeout", "180"]

# The cable graphs' delivered protocol: the same, on the RTX renderer, with the
# palette segmenter. Without the variable the runtime picks the gated SAM 3
# model whenever open-robot-skills is on the skill path.
CABLE_FLAGS = ["--no-privileged", "--perception", "vision", "--renderer", "rtx", "--bus-timeout", "600"]
CABLE_ENV = {"ROBOSIMSTUDIO_SEGMENTATION_BACKEND": "palette"}

TASK_CLASSES = OrderedDict(
    [
        ("tool_sorting", ("Tool Sorting", "tool_sort")),
        ("tool_hanging", ("Tool Hanging", "tool_hanging")),
        ("gear_meshing", ("Gear Meshing", "gear_mesh")),
        ("syringe_packing", ("Syringe Packing", "syringe_packing")),
        ("cable_insertion", ("Cable Insertion", "usbc_insert")),
        ("cable_routing", ("Cable Routing", "cable_route")),
    ]
)


# ------------------------------------------------------------------ building
def _tool_hanging(level: str, n: int) -> list[dict]:
    rows = [json.loads(line) for line in (SPECS / "tool_hanging" / level / "manifest.jsonl").read_text().splitlines()]
    out = []
    for row in rows[:n]:
        out.append(
            {
                "id": row["id"],
                "task": row["source_task"],
                "episode": int(row["source_episode"]),
                "document": f"benchmark/tool_hanging/{row['task_file']}",
                "initial": row["overrides"],
            }
        )
    return out


def _cable(case_name: str) -> tuple[list[dict], dict]:
    manifest = json.loads((SPECS / "cable_tasks" / "dataset" / "manifest.json").read_text())
    case = next(c for c in manifest["cases"] if c["name"] == case_name)
    scenes = {s["name"]: s for s in case["scenes"]}
    out = []
    for name in case["selected_tests"]:
        scene = scenes[name]
        episode = scene["episode"]
        out.append(
            {
                "id": name,
                "task": case["task"],
                # The dataset stamps each draw as episode 0 of seed 10000+k; the
                # suite's own seed is 0, so the same draw is episode 10000+k.
                "episode": int(episode["seed"]) + int(episode["episode_id"]),
                "document": f"benchmark/cable_tasks/dataset/{scene['file']}",
                "initial": dict(episode["overrides"]),
            }
        )
    return out, case


def _variants(task: str, names: list[str]) -> list[dict]:
    return [{"id": f"{task}/{name}", "task": f"{task}/{name}", "episode": 0} for name in names]


def build(n: int = 30) -> dict:
    """The manifest, from the frozen specs under ``benchmark/`` and the suites' own documents."""
    cells: dict[str, dict] = OrderedDict()

    def cell(key, level, *, suite, graph, flags, instances, selection, notes="", env=None):
        task_class = key
        cells[f"{task_class}/L{level}"] = {
            "task_class": TASK_CLASSES[task_class][0],
            "level": level,
            "suite": suite,
            "graph": graph,
            "flags": flags,
            "env": env or {},
            "selection": selection,
            "notes": notes,
            "instances": instances,
        }

    cell(
        "tool_sorting",
        1,
        suite="tool_sort",
        graph="gap_perception_loop",
        flags=[*UNPRIVILEGED, "--max-steps", "20000"],
        instances=_variants("tool_sort", [f"level1_{i}" for i in range(1, n + 1)]),
        selection="benchmark/tool_sort/level1: the 30 frozen documents, each a registered variant (episode 0).",
    )
    cell(
        "tool_sorting",
        2,
        suite="tool_sort",
        graph="gap_perception_loop",
        flags=[*UNPRIVILEGED, "--max-steps", "20000"],
        instances=[],
        selection="not frozen in this release",
        notes="Level 2 (cluttered tools) instance documents are not part of this release yet.",
    )
    # Tool hanging's graphs run past the documents' own budgets (measured
    # completions: about 5,800 steps at Level 1), so the evaluated recipes raise them.
    for level, name, budget in ((1, "easy", "8500"), (2, "medium", "22000")):
        cell(
            "tool_hanging",
            level,
            suite="tool_hanging",
            graph="gap_perception",
            flags=["--motion", "curobo", *UNPRIVILEGED, "--max-steps", budget],
            instances=_tool_hanging(name, n),
            selection=f"benchmark/tool_hanging/{name}/manifest.jsonl: the first {n} of 100 frozen instances.",
        )
    for level, family, width in ((1, "easy-pair", 2), (2, "medium-train", 3)):
        cell(
            "gear_meshing",
            level,
            suite="gear_mesh",
            graph="gap_perception",
            flags=["--motion", "curobo", *UNPRIVILEGED],
            instances=_variants("gear_mesh", [f"gearmesh-{family}-{i:0{width}d}" for i in range(1, n + 1)]),
            selection=f"the first {n} drawn `gearmesh-{family}` documents (each one draw, episode 0).",
            notes="No 30-instance selection was recorded for gear meshing; the first 30 by index are used.",
        )
    # The suite's task.py registers each trial document under a short name:
    # dispose_both_syringes_from_the_tray_tNN -> tray_pair_both_tNN (Level 1),
    # dispose_the_syringe_from_the_cluttered_tray_tNN -> tray_clutter_tNN (Level 2).
    for level, stem, name in (
        (1, "dispose_both_syringes_from_the_tray", "tray_pair_both"),
        (2, "dispose_the_syringe_from_the_cluttered_tray", "tray_clutter"),
    ):
        cell(
            "syringe_packing",
            level,
            suite="syringe_packing",
            graph="gap_perception",
            flags=["--motion", "curobo", *UNPRIVILEGED],
            instances=_variants("syringe_packing", [f"{name}_t{i:02d}" for i in range(n)]),
            selection=f"benchmark/syringe_packing/level{level}: the 30 `{stem}_tNN` trials, registered as `{name}_tNN`.",
            notes="The frozen copies under benchmark/ state profile vab_industrial@v1; the suite's documents, "
            "which are what run, state @v2.",
        )
    for task_class, prefix in (("cable_insertion", "usbcinsertion"), ("cable_routing", "cablerouting")):
        for level, name in ((1, "easy"), (2, "medium")):
            suffix = "insertplug" if task_class == "cable_insertion" else "routecable"
            instances, case = _cable(f"{prefix}-{name}-{suffix}")
            cell(
                task_class,
                level,
                suite=case["task"].split("/")[0],
                graph=case["graph"],
                flags=[*CABLE_FLAGS, "--settle-steps", str(case["settle_steps"])],
                env=CABLE_ENV,
                instances=instances,
                selection="benchmark/cable_tasks/dataset/manifest.json: `selected_tests` (farthest-point sampling "
                "over initialisations, chosen before any policy ran).",
                notes="Under this protocol the release does not reproduce the paper's cable rates; "
                "see docs/validation/cable.md.",
            )
    return {
        "name": "VABAR",
        "version": "1.0",
        "instances_per_cell": n,
        "note": "Each instance is (task, episode) on the registered suites; `document` is the frozen copy it matches.",
        "cells": cells,
    }


# ------------------------------------------------------------------ running
def load() -> dict:
    return json.loads(MANIFEST.read_text())


def _groups(instances: list[dict]) -> OrderedDict[str, list[int]]:
    groups: OrderedDict[str, list[int]] = OrderedDict()
    for inst in instances:
        groups.setdefault(inst["task"], []).append(int(inst["episode"]))
    return groups


def commands(cell: dict, *, limit: int = 0, solve: str = "graph", extra: list[str] = ()) -> list[list[str]]:
    """One ``vabar run`` argument list per task the cell's instances live on."""
    instances = cell["instances"][: limit or None]
    out = []
    for task, episodes in _groups(instances).items():
        argv = ["--task", task, "--episodes", ",".join(str(e) for e in episodes), "--solve", solve]
        if solve == "graph":
            argv += ["--graph", cell["graph"], *cell["flags"]]
        out.append(argv + list(extra))
    return out


def verify(cell: dict, *, limit: int = 0, atol: float = 1e-6) -> list[tuple[str, bool, str]]:
    """Draw each instance's episode and compare it to the frozen transforms, where recorded.

    The comparison is on the sampler's own output -- the ``object_xforms`` and
    ``static_xforms`` an episode carries, in the frame the sampler states them
    in -- so it needs no scene, and it checks exactly the claim the manifest
    makes: that ``(task, episode)`` is the draw the frozen document recorded.
    """
    import numpy as np

    from . import install

    install()
    from robosimstudio_bench.taskbuild.episodes import make_episode
    from robosimstudio_bench.taskbuild.registry import get_task

    results = []
    for inst in cell["instances"][: limit or None]:
        initial = inst.get("initial") or {}
        recorded = {**(initial.get("static_xforms") or {}), **(initial.get("object_xforms") or {})}
        if not recorded:
            results.append((inst["id"], True, "no recorded transforms"))
            continue
        drawn = dict(make_episode(get_task(inst["task"]), int(inst["episode"])).overrides)
        sampled = {**(drawn.get("static_xforms") or {}), **(drawn.get("object_xforms") or {})}
        missing = sorted(set(recorded) - set(sampled))
        worst = 0.0
        for name in set(recorded) & set(sampled):
            worst = max(
                worst, float(np.abs(np.asarray(sampled[name], float) - np.asarray(recorded[name], float)).max())
            )
        ok = worst <= atol and not missing
        results.append((inst["id"], ok, f"max |d| {worst:.1e}" + (f"; not drawn: {missing}" if missing else "")))
    return results


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="vabar bench", description=__doc__.splitlines()[0])
    parser.add_argument("--list", action="store_true", help="list the cells and their instance counts")
    parser.add_argument("--cell", help="task_class/L<level>, e.g. tool_hanging/L1")
    parser.add_argument("--solve", default="graph", help="graph (the cell's reference graph), routine, idle, ...")
    parser.add_argument("--limit", type=int, default=0, help="run only the first N instances")
    parser.add_argument("--print", action="store_true", help="print the vabar run commands and exit")
    parser.add_argument("--verify", action="store_true", help="check resets against the frozen transforms")
    parser.add_argument("--build", action="store_true", help=argparse.SUPPRESS)
    args, extra = parser.parse_known_args(argv)

    if args.build:
        MANIFEST.write_text(json.dumps(build(), indent=1) + "\n")
        print(f"wrote {MANIFEST.relative_to(REPO)}")
        return 0
    manifest = load()
    if args.list or not args.cell:
        for key, cell in manifest["cells"].items():
            print(f"{key:20s} {len(cell['instances']):3d}  {cell['suite']:16s} graph={cell['graph']}")
        return 0
    cell = manifest["cells"][args.cell]
    if not cell["instances"]:
        print(f"{args.cell}: {cell['selection']}. {cell['notes']}", file=sys.stderr)
        return 2
    if args.verify:
        rows = verify(cell, limit=args.limit)
        for name, ok, detail in rows:
            print(f"{'ok ' if ok else 'BAD'} {name}: {detail}")
        return 0 if all(ok for _, ok, _ in rows) else 1

    runs = commands(cell, limit=args.limit, solve=args.solve, extra=extra)
    env = cell.get("env", {}) if args.solve == "graph" else {}
    if args.print:
        prefix = "".join(f"{k}={shlex.quote(v)} " for k, v in env.items())
        for argv_ in runs:
            print(prefix + "python -m vabar run " + shlex.join(argv_))
        return 0
    for key, value in env.items():
        os.environ.setdefault(key, value)
    from .run import main as run

    status = 0
    for argv_ in runs:
        status |= run(argv_)
    return status


if __name__ == "__main__":
    if "--build" in sys.argv:
        raise SystemExit(main(["--build"]))
    raise SystemExit(main())
