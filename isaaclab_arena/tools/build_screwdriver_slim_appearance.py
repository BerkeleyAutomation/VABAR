"""Author the slim screwdriver's AUTOLab v1.0 appearance as a visual-only USD layer.

AUTOLab draws ``screwdriver_slim`` from ``screwdriver_1.obj`` with
``material_colors=True``: each MTL section becomes an untextured plastic shape in
its ``Kd`` colour (blue and green handle, dark grey and pale steel shaft), plus a
3 mm red ``visual_markers`` sphere on the tip. Arena's ``vabar__screwdriver_slim``
is the same mesh, face for face, with SimReady textures that render it plain green.

This writes ``payloads/autolab_appearance.usda``, which the asset wrapper
sublayers. It deactivates the SimReady material subsets, adds one subset per MTL
section, binds each to a ``UsdPreviewSurface`` with the colour and finish
AUTOLab's RTX renderer hands the path tracer, and adds the tip marker as a
non-colliding sphere. Geometry, mass, inertia and colliders are unchanged.

Run in AUTOLab's own environment (it supplies ``robosimstudio``, ``trimesh``
and ``pxr``), with the pinned AUTOLab checkout as the first argument and
isaaclab_arena_vabar's asset root as the second.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ASSET = "vabar__screwdriver_slim"
MESH = "/Asset/Geometry/Visual_obj_00/Visual_mesh_00"
SHAPE = "/Asset/Geometry/Visual_obj_00"
SECTIONS = {
    # MTL section name -> subset/material name in the Arena asset.
    "0.000000_0.000000_0.752941_0.000000_0.000000": "autolab_handle_blue",
    "0.000000_0.752941_0.000000_0.000000_0.000000": "autolab_handle_green",
    "0.250980_0.250980_0.250980_0.000000_0.000000": "autolab_shaft_dark",
    "0.792157_0.819608_0.933333_0.000000_0.000000": "autolab_shaft_steel",
}


def build(source: Path, assets: Path) -> Path:
    sys.path.insert(0, str(source))
    import numpy as np
    import trimesh
    from pxr import Sdf, Usd, UsdGeom, UsdShade
    from robosimstudio.core.render.finish import finish_for
    from robosimstudio.core.render.palette import srgb_to_linear
    from robosimstudio.solvers.render.rtx import PALETTE_IS_DISPLAY
    from tasks.tool_hanging.assets.records import screwdriver_slim

    spec = screwdriver_slim()
    assert PALETTE_IS_DISPLAY, "AUTOLab's calibrated RTX renderer decodes display colours"
    obj = Path(spec.asset.path)
    if spec.asset.scale != 1.0:
        raise ValueError(f"expected an unscaled screwdriver_slim, got scale {spec.asset.scale}")

    # Each face's MTL section, in file order, and each section's colour as AUTOLab's
    # _add_material_visuals reads it (trimesh, diffuse / 255).
    obj_faces, sections, section = [], [], None
    for line in obj.read_text().splitlines():
        fields = line.split()
        if fields[:1] == ["usemtl"]:
            section = fields[1]
        elif fields[:1] == ["f"]:
            obj_faces.append([int(token.split("/")[0]) - 1 for token in fields[1:]])
            sections.append(SECTIONS[section])
    scene = trimesh.load(str(obj), force="scene", process=False)
    colors, section_faces = {}, {}
    for node in scene.graph.nodes_geometry:
        _, geometry = scene.graph.get(node)
        part = scene.geometry[geometry]
        name = SECTIONS[part.visual.material.name]
        colors[name] = tuple(np.asarray(part.visual.material.diffuse, dtype=float)[:3] / 255.0)
        section_faces[name] = len(part.faces)

    asset_dir = assets / ASSET
    out = asset_dir / "payloads/autolab_appearance.usda"
    # Read the wrapper without the layer this rewrites, so a rerun starts from SimReady's subsets.
    wrapper = Usd.Stage.Open(str(asset_dir / f"{ASSET}.usda"))
    wrapper.MuteLayer(str(out))
    mesh = UsdGeom.Mesh(wrapper.GetPrimAtPath(MESH))
    counts = np.asarray(mesh.GetFaceVertexCountsAttr().Get())
    indices = np.asarray(mesh.GetFaceVertexIndicesAttr().Get())
    # SimReady kept the OBJ's topology face for face; coincident faces of different
    # sections rule out matching by position, so require the identity and map by index.
    if not (np.all(counts == 3) and np.array_equal(indices.reshape(-1, 3), np.asarray(obj_faces))):
        raise ValueError(f"{ASSET} no longer has screwdriver_1.obj's face list")
    faces: dict[str, list[int]] = {name: [] for name in SECTIONS.values()}
    for face, name in enumerate(sections):
        faces[name].append(face)
    if {name: len(ids) for name, ids in faces.items()} != section_faces:
        raise ValueError(f"OBJ sections {section_faces} disagree with the face list")

    out.parent.mkdir(exist_ok=True)
    out.unlink(missing_ok=True)
    layer = Sdf.Layer.CreateNew(str(out))
    stage = Usd.Stage.Open(layer)
    stage.SetEditTarget(layer)
    layer.comment = (
        f"Generated by tools/build_screwdriver_slim_appearance.py from AUTOLab v1.0 {obj.relative_to(source)}. "
        "Visual only: geometry, mass, inertia and colliders come from the wrapper."
    )

    def material(name: str, color) -> UsdShade.Material:
        finish = finish_for(color)
        mat = UsdShade.Material.Define(stage, f"/Asset/AutolabLooks/{name}")
        shader = UsdShade.Shader.Define(stage, f"{mat.GetPath()}/PreviewSurface")
        shader.CreateIdAttr("UsdPreviewSurface")
        shader.CreateInput("diffuseColor", Sdf.ValueTypeNames.Color3f).Set(
            tuple(round(float(c), 6) for c in srgb_to_linear(color))
        )
        shader.CreateInput("roughness", Sdf.ValueTypeNames.Float).Set(float(finish.roughness))
        shader.CreateInput("metallic", Sdf.ValueTypeNames.Float).Set(float(finish.metallic))
        shader.CreateInput("opacity", Sdf.ValueTypeNames.Float).Set(float(finish.opacity))
        mat.CreateSurfaceOutput().ConnectToSource(shader.ConnectableAPI(), "surface")
        return mat

    looks = {name: material(name, colors[name]) for name in SECTIONS.values()}

    mesh_over = stage.OverridePrim(MESH)
    for subset in UsdGeom.Subset.GetAllGeomSubsets(UsdGeom.Mesh(wrapper.GetPrimAtPath(MESH))):
        stage.OverridePrim(subset.GetPrim().GetPath()).SetActive(False)
    UsdShade.MaterialBindingAPI.Apply(mesh_over).Bind(looks["autolab_handle_green"])
    for name, face_ids in faces.items():
        subset = UsdGeom.Subset.Define(stage, f"{MESH}/{name}")
        subset.CreateElementTypeAttr(UsdGeom.Tokens.face)
        subset.CreateFamilyNameAttr(UsdShade.Tokens.materialBind)
        subset.CreateIndicesAttr(face_ids)
        UsdShade.MaterialBindingAPI.Apply(subset.GetPrim()).Bind(looks[name])

    for index, (position, radius, color) in enumerate(spec.visual_markers):
        marker = UsdGeom.Sphere.Define(stage, f"{SHAPE}/autolab_tip_marker_{index:02d}")
        marker.CreateRadiusAttr(float(radius))
        marker.CreateExtentAttr([(-radius,) * 3, (radius,) * 3])
        marker.AddTranslateOp().Set(tuple(float(v) for v in position))
        UsdShade.MaterialBindingAPI.Apply(marker.GetPrim()).Bind(
            material(f"autolab_tip_marker_{index:02d}", tuple(float(c) for c in color))
        )

    # Prims the wrapper already defines are opinions here, not definitions.
    for path in ("/Asset", "/Asset/Geometry", SHAPE, MESH):
        layer.GetPrimAtPath(path).specifier = Sdf.SpecifierOver
    layer.GetPrimAtPath("/Asset/AutolabLooks").typeName = "Scope"
    layer.Save()
    print(f"Authored {out}: " + ", ".join(f"{k} {len(v)} faces" for k, v in faces.items()), flush=True)
    return out


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("assets", type=Path)
    args = parser.parse_args()
    build(args.source.resolve(), args.assets.resolve())
